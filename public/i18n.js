export function translate(language, key, values = {}) {
  const pair = strings[key];
  const text = pair ? pair[language === 'fr' ? 0 : 1] : key;
  return text.replace(/\{(\w+)\}/g, (match, name) => values[name] === undefined ? match : String(values[name]));
}
export function preferredLanguage(saved, browserLanguages = []) {
  if (saved === 'en' || saved === 'fr') return saved;
  for (const tag of browserLanguages) {
    const language = String(tag).toLowerCase().split('-')[0];
    if (language === 'fr' || language === 'en') return language;
  }
  return 'en';
}
